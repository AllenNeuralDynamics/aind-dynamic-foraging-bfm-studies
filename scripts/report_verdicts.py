#!/usr/bin/env python3
"""Write a study's verdicts from its version-2 reports' frontmatter claims.

    python scripts/report_verdicts.py studies/<study>      # or: make -C studies/<study> verdicts

A version-2 report's `claims` are the only home of its verdict (schemas/README.md, Version-2
reports). This script copies them, never edits them, into two generated blocks:

  analysis/reports/INDEX.md   a table of every version-2 report: title, status, question, claims
  README.md `## Verdict`      the claims of every live version-2 report

Each block sits between `<!-- BEGIN verdicts -->` and `<!-- END verdicts -->`; everything around
it is hand-written and kept. A missing block is added (INDEX: at the end; README: under
`## Verdict`). A study with no version-2 report and no block is left alone, so version-1
reports and their hand-written rows are never touched. scripts/check_provenance.py renders
the same blocks and warns (`verdict-stale`) when the committed ones differ.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

import yaml

REPORT_NAME = re.compile(r"^r(?P<n>[0-9]+)-(?P<slug>[a-z0-9]+(-[a-z0-9]+)*)\.md$")
FRONTMATTER = re.compile(r"\A---\n(.*?)\n---\n", re.S)
# script-written regions of a report (result-N, methods), HTML comments and fenced code
MARKED = re.compile(r"<!-- BEGIN ([\w.-]+) -->.*?<!-- END \1 -->", re.S)
COMMENT = re.compile(r"<!--.*?-->", re.S)
FENCE = re.compile(r"^```.*?^```[^\n]*$", re.S | re.M)
HEADING = re.compile(r"^(#{1,2}) +(.*?)[ \t]*$", re.M)
BLOCK = re.compile(r"<!-- BEGIN verdicts -->\n?(.*?)<!-- END verdicts -->", re.S)

INDEX_NOTE = ("<!-- generated by `make verdicts` from the version-2 reports' frontmatter claims; "
              "edit the claims, not this table -->")
README_NOTE = ("<!-- generated by `make verdicts` from the live version-2 reports' frontmatter claims; "
               "edit the claims, not this block -->")
NO_LIVE = "No live report with claims yet."


def blank(text: str, pattern: re.Pattern) -> str:
    """Blank every match but keep its newlines, so line numbers still point into the file."""
    return pattern.sub(lambda m: re.sub(r"[^\n]", " ", m.group()), text)


def hand_written(body: str) -> str:
    """A report body without its script-written blocks, HTML comments and fenced code."""
    return blank(blank(blank(body, MARKED), COMMENT), FENCE)


def headings(body: str) -> list[str]:
    """The `#` and `##` headings of the hand-written body, as written (`## Question`)."""
    return [f"{m[1]} {m[2]}" for m in HEADING.finditer(hand_written(body))]


def section(body: str, heading: str) -> str:
    """The first paragraph under `heading`, on one line; '' when the section is missing."""
    text = hand_written(body)
    m = re.search(rf"^{re.escape(heading)}[ \t]*$", text, re.M)
    if not m:
        return ""
    rest = re.split(r"^#{1,2} ", text[m.end():], maxsplit=1, flags=re.M)[0]
    para = next((p for p in re.split(r"\n\s*\n", rest) if p.strip()), "")
    return " ".join(para.split())


def v2_reports(study: Path) -> list[tuple[str, dict, str]]:
    """(file name, frontmatter, body) of the study's version-2 reports, in report order."""
    found = []
    for p in (study / "analysis" / "reports").glob("r*.md"):
        m = REPORT_NAME.match(p.name)
        text = p.read_text(errors="replace") if m else ""
        fm = FRONTMATTER.match(text)
        try:
            data = yaml.safe_load(fm.group(1)) if fm else None
        except yaml.YAMLError:
            data = None
        if isinstance(data, dict) and data.get("schema_version") == 2:
            found.append((int(m["n"]), p.name, data, text[fm.end():]))
    return [(name, fm, body) for _, name, fm, body in sorted(found)]


def _cell(text) -> str:
    return " ".join(str(text).split()).replace("|", "\\|")


def _title(name: str, fm: dict, body: str) -> str:
    h1 = next((h[2:] for h in headings(body) if h.startswith("# ")), None)
    return h1 or str(fm.get("id") or name)


def _claims(fm: dict) -> list[tuple[str, str]]:
    claims = fm.get("claims") if isinstance(fm.get("claims"), list) else []   # else: a schema error
    return [(str(c.get("id")), str(c.get("text"))) for c in claims if isinstance(c, dict)]


def _status(fm: dict) -> str:
    status = str(fm.get("status"))
    if status == "draft" and fm.get("draft_reason"):
        return f"draft: {fm['draft_reason']}"
    succ = fm.get("superseded_by")
    if status == "superseded" and isinstance(succ, dict):
        return f"superseded by {succ.get('study')}/{succ.get('report')}"
    return status


def index_block(study: Path) -> str:
    rows = ["| report | status | question | verdict |", "|---|---|---|---|"]
    for name, fm, body in v2_reports(study):
        verdict = "<br>".join(f"**{i}.** {t}" for i, t in _claims(fm))
        rows.append(f"| [{_cell(_title(name, fm, body))}]({name}) | {_cell(_status(fm))} | "
                    f"{_cell(section(body, '## Question'))} | {_cell(verdict)} |")
    return INDEX_NOTE + "\n\n" + "\n".join(rows) + "\n\n"     # a blank line ends the table


def readme_block(study: Path) -> str:
    parts = [README_NOTE]
    live = [r for r in v2_reports(study) if r[1].get("status") == "live"]
    for name, fm, body in live:
        parts.append(f"**[{_title(name, fm, body)}](analysis/reports/{name})**")
        parts.append("\n".join(f"- **{i}.** {' '.join(t.split())}" for i, t in _claims(fm)))
    if not live:
        parts.append(NO_LIVE)
    return "\n\n".join(parts) + "\n\n"


def wrap(inner: str) -> str:
    return f"<!-- BEGIN verdicts -->\n{inner}<!-- END verdicts -->"


def current(text: str) -> str | None:
    """The generated block's content in `text`, or None when it has none."""
    m = BLOCK.search(text)
    return m.group(1) if m else None


def expected(study: Path) -> dict[Path, str]:
    """Each file that must carry a generated block -> the block's content. A file is listed when
    the study has a version-2 report, or when the file already has a block."""
    has_v2 = bool(v2_reports(study))
    out = {}
    for path, render in ((study / "analysis" / "reports" / "INDEX.md", index_block),
                         (study / "README.md", readme_block)):
        if path.exists() and (has_v2 or current(path.read_text()) is not None):
            out[path] = render(study)
    return out


def apply(path: Path, inner: str) -> str:
    """`path`'s text with its generated block set to `inner`, inserting the block if missing."""
    text = path.read_text()
    if current(text) is not None:
        return BLOCK.sub(lambda _: wrap(inner), text, count=1)
    if path.name == "README.md":
        m = re.search(r"^## Verdict[ \t]*\n", text, re.M)
        if m:
            return text[:m.end()] + "\n" + wrap(inner) + "\n" + text[m.end():]
        return text.rstrip("\n") + "\n\n## Verdict\n\n" + wrap(inner) + "\n"
    return text.rstrip("\n") + "\n\n" + wrap(inner) + "\n"


def write(study: Path) -> list[Path]:
    changed = []
    for path, inner in expected(study).items():
        new = apply(path, inner)
        if new != path.read_text():
            path.write_text(new)
            changed.append(path)
    return changed


def main(argv: list[str] | None = None) -> int:
    args = sys.argv[1:] if argv is None else argv
    if len(args) != 1 or not Path(args[0], "analysis", "reports").is_dir():
        sys.exit("usage: report_verdicts.py studies/<study>   (a study directory with analysis/reports/)")
    for path in write(Path(args[0])):
        print(f"  wrote verdicts in {path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
