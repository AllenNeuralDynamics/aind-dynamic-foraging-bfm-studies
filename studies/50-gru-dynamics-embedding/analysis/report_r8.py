"""r8: regenerate the numbers block of ``reports/r8-gru-vs-q-learning.md`` from the H JSONs.

    python analysis/report_r8.py
"""

from __future__ import annotations

import json
import re
from pathlib import Path

ANALYSIS = Path(__file__).resolve().parent
REPORT = ANALYSIS / "reports" / "r8-gru-vs-q-learning.md"
BEGIN, END = "<!-- BEGIN result-8 -->", "<!-- END result-8 -->"


def load(name: str) -> dict:
    return json.loads((ANALYSIS / name).read_text())


def block() -> str:
    h3, h4 = load("h3_q_phase_portraits.json"), load("h4_scenarios.json")
    lines = ["[regenerated by `analysis/report_r8.py` — do not edit by hand]", "",
             "### H3 Dynamics in Q-learning's coordinates", "",
             f"GRU Q̂ decoded from its state (target: {h3['decoder_target']}), held-out R² "
             + ", ".join(f"{k} {v:.3f}" for k, v in h3["decoding_heldout_r2"].items()) + ".", "",
             "One-trial change ΔQ = a + b·Q_chosen + c·Q_unchosen, per input and model (a / b / c, R²):", "",
             "| input | side | GRU | Hattori | Bari |", "|---|---|---|---|---|"]
    for name, models in h3["update_regressions"].items():
        for side in ("chosen", "unchosen"):
            cells = [f"{o[side]['a']:+.3f} / {o[side]['b_Qchosen']:+.3f} / {o[side]['c_Qunchosen']:+.3f} ({o[side]['r2']:.2f})"
                     for o in models.values()]
            lines.append(f"| {name} | {side} | " + " | ".join(cells) + " |")
    lines += ["", "![H3](../fig_H3_q_phase_portraits.png)", "", "### H4 Canonical scenarios", "",
              f"{h4['n_mice']} mice; {h4['start']}; context: {h4['context']}. Median P(right) across mice:", ""]
    for name, sc in h4["scenarios"].items():
        lines.append(f"- **{name}** — " + "; ".join(f"{m}: " + ", ".join(f"{x:.2f}" for x in v)
                                                  for m, v in sc["median_p_right"].items()))
    f, g = h4["sweep_F_return_after_failed_switch"], h4["sweep_G_stay_through_losses_new_side"]
    lines += ["", "| sweep | model | values |", "|---|---|---|"]
    lines += [f"| F: P(return to R) after n R+ then L−, n = {f['n'][0]}…{f['n'][-1]} | {m} | "
              + ", ".join(f"{x:.2f}" for x in v) + " |" for m, v in f["median"].items()]
    lines += [f"| G: P(stay on L) after 6 R+ then k L−, k = {g['k'][0]}…{g['k'][-1]} | {m} | "
              + ", ".join(f"{x:.2f}" for x in v) + " |" for m, v in g["median"].items()]
    if "alternation_zigzag_D" in h4:
        lines += ["", "Scenario D, mean |ΔP(right)| per trial after trial 6 (median across mice): "
                  + ", ".join(f"{m} {v:.3f}" for m, v in h4["alternation_zigzag_D"].items()) + "."]
    lines += ["", "![H4](../fig_H4_scenarios.png)"]
    h1 = load("h1_model_ladder.json")
    lines += ["", "### H1 Model ladder (each rung fitted per mouse to the GRU's P(right), scored on the animals)", "",
              "Reference likelihoods: " + ", ".join(f"{k} {v:.4f}" for k, v in h1["reference_likelihood"].items()) + ".", "",
              "| rung | animal likelihood | gap closed (CTT → GRU) | mice beating CTT | cross-entropy to GRU | median parameters |",
              "|---|---:|---:|---:|---:|---|"]
    keep = {"R0": ["a_rew", "a_unrew", "forget", "beta"], "R1": ["w_ck"], "R2": ["lam_T", "w_T"], "R3": ["lam_T", "w_T", "kappa_unrew"],
            "R4": ["rho"], "R5": ["w_ck", "w_ck_unrew"]}
    for name, r in h1["results"].items():
        pm = ", ".join(f"{k} {r['params_median'][k]:.3g}" for k in keep[name.split(" ")[0]])
        lines.append(f"| {name} | {r['animal_likelihood']:.4f} | {100 * r['gap_closed_vs_ctt']:+.0f}% | "
                     f"{100 * r['frac_mice_beat_ctt']:.0f}% | {r['fit_cross_entropy_to_gru']:.5f} | {pm} |")
    lines += ["", "C4e signature error (mean |model − animals|):", "", "| curve | GRU | " + " | ".join(n.split(" ")[0] for n in h1["rungs"]) + " |",
              "|---|" + "---:|" * (len(h1["rungs"]) + 1)]
    for curve, errs in h1["signature_errors"].items():
        lines.append(f"| {curve} | {errs['gru']:.3f} | " + " | ".join(f"{errs[n]:.3f}" for n in h1["rungs"]) + " |")
    lines += ["", "![H1](../fig_H1_model_ladder.png)"]
    h2 = load("h2_learning_rate.json")
    lines += ["", "### H2 Effective learning rate by state (one reward flipped, next trial, log-odds)", "",
              f"{h2['n_probes']:,} probes; GRU one-step replay vs cached logits median |Δ| {h2['gru_replay_median_abs_diff']:.4f}. "
              "Mean effect / coefficient of variation across probes: "
              + ", ".join(f"{m} {h2['mean_effect'][m]:.3f} / {h2['cv_of_effect_across_probes'][m]:.2f}" for m in h2["mean_effect"]) + ".", ""]
    for name, models in h2["by_state"].items():
        cells = []
        for m, d in models.items():
            if "mean" in d:
                cells.append(f"{m}: " + ", ".join(f"{v:.2f}" for v in d["mean"]))
            else:
                cells.append(f"{m}: " + ", ".join(f"{k} {v:.2f}" for k, v in d.items()))
        lines.append(f"- **{name}** — " + "; ".join(cells))
    return "\n".join(lines + ["", "![H2](../fig_H2_learning_rate.png)"])


def main() -> None:
    text = REPORT.read_text()
    pattern = re.compile(re.escape(BEGIN) + r".*?" + re.escape(END), re.S)
    if len(pattern.findall(text)) != 1:
        raise AssertionError(f"{REPORT.name} must contain exactly one {BEGIN} … {END} pair")
    REPORT.write_text(pattern.sub(lambda _: f"{BEGIN}\n{block()}\n{END}", text))
    print(f"Wrote {REPORT}")


if __name__ == "__main__":
    main()
