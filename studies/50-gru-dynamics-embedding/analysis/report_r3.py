"""r3: regenerate the numbers block of ``reports/r3-dynamics.md`` from ``d_dynamics.json``.

    python analysis/report_r3.py
"""

from __future__ import annotations

import json
import re
from pathlib import Path

ANALYSIS = Path(__file__).resolve().parent
REPORT = ANALYSIS / "reports" / "r3-dynamics.md"
BEGIN, END = "<!-- BEGIN result-3 -->", "<!-- END result-3 -->"


def block() -> str:
    d = json.loads((ANALYSIS / "d_dynamics.json").read_text())
    p = d["parity"]
    lines = ["[regenerated by `analysis/report_r3.py` — do not edit by hand]", "",
             f"Step parity on {p['n_sessions']} real sessions: median |Δlogit| {p['median_abs_err']:.4f} "
             f"(max {p['max_abs_err']:.3f}) vs the A1 table. Search: {d['n_init']} real-state starts per context × "
             f"input; Adam ({d['n_steps']} steps, decaying) and {d['n_forward']} forward iterations, each refined by "
             f"{d['n_newton']} damped Newton steps in {d['precision']}; fixed point if ½‖F(h)−h‖² < {d['fixed_tol']:g}.",
             "", "| context | input | fixed points (stable / unstable) | logit(right) | slowest \\|λ\\| | τ (trials) | "
             "slow mode · readout | candidates converged |", "|---|---|---|---|---:|---:|---:|---:|"]
    for g, entry in d["contexts"].items():
        for u, rec in entry["inputs"].items():
            fps = rec["fixed_points"]
            stable = [f for f in fps if f["stable"]]
            main = min(stable, key=lambda f: -abs(f["logit_right"])) if stable else (fps[0] if fps else None)
            if main is None:
                lines.append(f"| {g} | {u} | 0 | — | — | — | — | {rec['frac_candidates_converged']:.2f} |")
                continue
            tau = main["tau_trials"][0]
            lines.append(f"| {g} | {u} | {len(stable)} / {len(fps) - len(stable)} | "
                         + ", ".join(f"{f['logit_right']:+.2f}" for f in fps)
                         + f" | {main['top_abs_eig'][0]:.4f} | {tau:.0f} | {main['slow_mode_overlap'][0]['readout']:.2f} | "
                         f"{rec['frac_candidates_converged']:.2f} |" if tau is not None else " | — | — |")
    lines += ["", "Logit and λ columns describe the most extreme stable fixed point per row; all fixed points, their "
              "PC1–6 coordinates and the overlap of the three slowest modes with the readout and PCs 1/2/5 are in "
              "`d_dynamics.json`.", "", "![D1](../fig_D1_flow_fields.png)", "![D2](../fig_D2_fixed_points.png)"]
    return "\n".join(lines)


def main() -> None:
    text = REPORT.read_text()
    pattern = re.compile(re.escape(BEGIN) + r".*?" + re.escape(END), re.S)
    if len(pattern.findall(text)) != 1:
        raise AssertionError(f"{REPORT.name} must contain exactly one {BEGIN} … {END} pair")
    REPORT.write_text(pattern.sub(lambda _: f"{BEGIN}\n{block()}\n{END}", text))
    print(f"Wrote {REPORT}")


if __name__ == "__main__":
    main()
