"""r6: regenerate the numbers block of ``reports/r6-integration-axis.md`` from the I JSONs.

    python analysis/report_r6.py
"""

from __future__ import annotations

import json
import re
from pathlib import Path


ANALYSIS = Path(__file__).resolve().parent
REPORT = ANALYSIS / "reports" / "r6-integration-axis.md"
BEGIN, END = "<!-- BEGIN result-6 -->", "<!-- END result-6 -->"


def load(name: str) -> dict:
    return json.loads((ANALYSIS / name).read_text())


def matrix(m, labels) -> list[str]:
    head = "| | " + " | ".join(labels) + " |"
    rows = [f"| {lab} | " + " | ".join(f"{v:+.2f}" for v in row) + " |" for lab, row in zip(labels, m)]
    return [head, "|---|" + "---:|" * len(labels), *rows]


def block() -> str:
    i1, i2, i3 = load("i1_cluster_axes.json"), load("i2_tdr.json"), load("i3_tdr_dynamics.json")
    clusters = i1["clusters"]
    lines = ["[regenerated by `analysis/report_r6.py` — do not edit by hand]", "",
             "### I1 Per-cluster encoding axes (context and trial position partialled out)", "",
             f"Cluster sizes: " + ", ".join(f"{c} {n:,}" for c, n in zip(clusters, i1["n"])) + "."]
    for v in i1["values"][:2]:
        e = i1["partial"]["by_value"][v]
        lines += ["", f"Cosine of the {v} encoding axis across clusters:", "", *matrix(e["cosine_across_clusters"], clusters),
                  "", "Cosine with the readout r: " + ", ".join(f"{c} {x:+.2f}" for c, x in zip(clusters, e["cosine_with_readout"]))
                  + "; share of within-cluster state variance along the axis: "
                  + ", ".join(f"{x:.2f}" for x in e["share_of_cluster_variance"]) + "."]
    cross = i1["partial"]["logit_axis_vs_external_value_axes_per_cluster"]
    lines += ["", "Within each cluster, logit axis · ΔQ axis: " + ", ".join(f"{x:+.2f}" for x in cross["logit(right) vs Hattori ΔQ"])
              + "; logit axis · P(rew|R) − P(rew|L) axis: " + ", ".join(f"{x:+.2f}" for x in cross["logit(right) vs P(rew|R) − P(rew|L)"]) + ".",
              "Curvature (local logit axis per value tercile · the cluster's axis): "
              + "; ".join(f"{c} " + "/".join(f"{x:.2f}" for x in v["tercile_vs_cluster_axis"])
                          for c, v in i1["curvature_partial_logit"].items()) + ".",
              "", "![I1](../fig_I1_cluster_axes.png)", "", "### I2 Targeted dimensionality reduction", "",
              f"{i2['n_trials']:,} trials; regressors {', '.join(i2['terms'])} + {', '.join(i2['nuisances'])}. "
              f"Task + nuisance R² of the state {i2['task_plus_nuisance_r2']:.3f}; the 5-d TDR subspace holds "
              f"{100 * i2['variance_share_tdr_subspace']:.1f}% of state variance (top 5 PCs: "
              f"{100 * i2['variance_share_top_pcs_same_dim']:.1f}%). Lobe value axes (β_v ± β_vc) cosine "
              f"{i2['lobe_axes_cosine']:+.2f}; with the readout: "
              + ", ".join(f"{k} {v:+.2f}" for k, v in i2["lobe_axes_cosine_with_readout"].items()) + ".",
              "", "![I2](../fig_I2_tdr.png)", "", "### I3 The value coordinate across transitions", "",
              "| input (trial t) | from | n | slope v(t+1) on v(t) | R² | mean jump: value | choice | reward |",
              "|---|---|---:|---:|---:|---:|---:|---:|"]
    for key, r in i3["transitions"].items():
        name, src = key.split(" | ")
        j = r["mean_jump"]
        lines.append(f"| {name} | {src} | {r['n']:,} | {r['slope']:.2f} | {r['r2']:.2f} | {j['value']:+.2f} | "
                     f"{j['choice']:+.2f} | {j['reward']:+.2f} |")
    att = i3["attractors_all_sessions_context"]
    lines += ["", "Stable fixed point of each constant input (all-sessions mean context) on the value axis: "
              + ", ".join(f"{k} {', '.join(f'{p[0]:+.2f}' for p in v['tdr'])} (logit {', '.join(f'{x:+.2f}' for x in v['logit_right'])})"
                          for k, v in att.items()) + "."]
    rl = []
    for name, m in load("rl_fit_medians.json")["medians"].items():   # frozen by freeze_rl_fit_medians.py
        rl.append(f"{name} {m['param']} median {m['median']:.2f}")
    slopes = [r["slope"] for r in i3["transitions"].values()]
    lines += [f"Implied per-trial update fraction 1 − slope: {1 - max(slopes):.2f}–{1 - min(slopes):.2f}; fitted RL for "
              "reference: " + ", ".join(rl) + ".", "", "![I3](../fig_I3_tdr_dynamics.png)"]
    return "\n".join(lines + distilled())


def distilled() -> list[str]:
    i4, i5, i6 = load("i4_distilled_model.json"), load("i5_mouse_dynamics.json"), load("i6_rl_transitions.json")
    groups, pooled = i4["groups"], i4["pooled"]
    lines = ["", "### I4 Distilled one-variable model", "",
             "| group | n | λ | v* |", "|---|---:|---:|---:|"]
    lines += [f"| {g} | {n:,} | {lam:.2f} | {t:+.2f} |" for g, n, lam, t in zip(groups, pooled["n"], pooled["lam"], pooled["target"])]
    sim = i4["simulated_vs_gru"]
    lines += ["", "Eval likelihood: " + ", ".join(f"{k} {v:.4f}" for k, v in i4["likelihood"].items()) + ".",
              f"Teacher-forced readout R² (logit ≈ a·v + b[last input]) {i4['teacher_forced_readout_r2']:.3f}; simulated v vs "
              f"the GRU's v: corr {sim['corr_v']:.3f} per mouse, {sim['corr_v_pooled']:.3f} pooled; logit corr "
              f"{sim['corr_logit']:.3f}. Per-mouse distilled model beats CTT in {100 * i4['per_mouse_frac_beats_ctt']:.1f}% "
              f"of {i4['n_mice']} mice.", "", "![I4](../fig_I4_distilled_model.png)", "",
              "### I5 Per-mouse dynamics parameters vs behaviour and the embedding", "",
              "Spearman across mice (rows: I4 per-mouse parameters; columns: F3 GRU kernel features), and rank R² "
              "decoding each parameter from the 4-d embedding (shuffle 95th percentile):", "",
              "| parameter | " + " | ".join(i5["behaviour_features"]) + " | embedding rank R² | null 95% | 10/50/90th pct |",
              "|---|" + "---:|" * (len(i5["behaviour_features"]) + 3)]
    for d in i5["dynamics_features"]:
        dec = i5["embedding_decoding"][d]
        lines.append(f"| {d} | " + " | ".join(f"{i5['spearman'][f][d]:+.2f}" for f in i5["behaviour_features"])
                     + f" | {dec['rank_r2']:.2f} | {dec['null_95']:.2f} | "
                     + " / ".join(f"{x:.2f}" for x in i5["per_mouse_summary"][d]) + " |")
    lines += ["", "![I5](../fig_I5_mouse_dynamics.png)", "", "### I6 The same transitions in the RL models", "",
              "Per group: pooled λ (median of per-mouse λ) / target / R².", "",
              "| group | " + " | ".join(f"{i6['models'][m]} {k}" for m in i6["models"] for k in ("state", "logit")) + " |",
              "|---|" + "---:|" * (2 * len(i6["models"]))]
    for g in i6["fit_groups"]:
        cells = []
        for m in i6["models"]:
            for k in ("state", "logit"):
                f = i6["fits"][m][k]
                cells.append(f"{f['lam'][g]:.2f} ({f['lam_median_per_mouse'][g]:.2f}) / {f['target'][g]:+.2f} / {f['r2'][g]:.2f}")
        lines.append(f"| {groups[g]} | " + " | ".join(cells) + " |")
    lines += ["", f"State: {i6['variables']['state']}; logit: {i6['variables']['logit']}.", "",
              "![I6](../fig_I6_rl_transitions.png)"]
    return lines + second_variable()


def second_variable() -> list[str]:
    i7 = load("i7_second_variable.json")
    lines = ["", "### I7 A second carried coordinate", "",
             f"GRU {i7['gru_likelihood']:.4f}, CTT {i7['ctt_likelihood']:.4f}. Teacher-forced = the readout on the GRU's own "
             "coordinates; simulated = the distilled model run from the animals' inputs.", "",
             "| carried state | teacher-forced (pooled) | teacher-forced (per mouse) | simulated (per mouse) | simulated (pooled) "
             "| gap closed | update R² of u | sim corr of u |", "|---|---:|---:|---:|---:|---:|---:|---:|"]
    for name, r in i7["results"].items():
        u_r2 = f"{r['update_r2'][1]:.2f}" if len(r["update_r2"]) > 1 else "—"
        u_c = f"{r['corr_sim_vs_gru'][1]:.2f}" if len(r["corr_sim_vs_gru"]) > 1 else "—"
        lines.append(f"| {name} | {r['teacher_forced']:.4f} | {r['teacher_forced_per_mouse']:.4f} | {r['simulated_per_mouse']:.4f} "
                     f"| {r['simulated_pooled']:.4f} | {100 * r['gap_closed_per_mouse']:.0f}% | {u_r2} | {u_c} |")
    c = i7["readout_residual_axis"]
    lines += ["", f"Readout-residual axis: {100 * c['variance_share']:.1f}% of state variance; cosine with the TDR axes "
              + ", ".join(f"{k} {v:+.2f}" for k, v in c["cos_with_tdr_axes"].items()) + ". Within-cluster R² from choice and "
              f"choice×reward history (lags 2–10): v {c['v: within-cluster R² from lags 2–10']:.2f}, residual "
              f"{c['readout residual: within-cluster R² from lags 2–10']:.2f}.", "",
              "| lag | v: choice | v: choice×reward | residual: choice | residual: choice×reward |", "|---:|---:|---:|---:|---:|"]
    hv, hr = c["v: history weights"], c["readout residual: history weights"]
    for lag in range(2, c["history_lags"][1] + 1):
        lines.append(f"| {lag} | {hv[f'choice-{lag}']:+.3f} | {hv[f'choice×reward-{lag}']:+.3f} | "
                     f"{hr[f'choice-{lag}']:+.3f} | {hr[f'choice×reward-{lag}']:+.3f} |")
    return lines + ["", "![I7](../fig_I7_second_variable.png)"] + v_tests()


def v_tests() -> list[str]:
    i8 = load("i8_v_tests.json")
    clo, pert, kern = i8["closure_heldout_r2"], i8["perturbation"], i8["flip_kernels"]
    names = list(next(iter(clo.values())))
    lines = ["", "### I8 Causal tests of v", "", "Closure, held-out R² of v(t+1):", "",
             "| group | " + " | ".join(names) + " |", "|---|" + "---:|" * len(names)]
    lines += [f"| {g} | " + " | ".join(f"{d[n]:.4f}" for n in names) + " |" for g, d in clo.items()]
    lines += ["", f"Perturbation of v by ±{i8['delta']} (k = 1…{i8['K']}):", "",
              "| k | " + " | ".join(str(k) for k in pert["k"]) + " |", "|---|" + "---:|" * len(pert["k"])]
    for key, lab in (("measured_mean", "GRU Δv/δ"), ("predicted_mean", "Π λ (I4)"), ("spill_median", "share off v's axis"),
                     ("logit_per_unit_v", "Δlogit/δ")):
        lines.append(f"| {lab} | " + " | ".join(f"{x:.2f}" for x in pert[key]) + " |")
    lines += ["", "Flip kernels in log-odds units (k = 1…10): reward effect / choice effect unrewarded / choice effect "
              "rewarded:", ""]
    for model, parts in kern.items():
        for part, k in parts.items():
            lines.append(f"- {model}, {part}: R " + ", ".join(f"{x:.2f}" for x in k["reward effect"])
                         + " | C₀ " + ", ".join(f"{x:.2f}" for x in k["choice effect, unrewarded"])
                         + " | C₁ " + ", ".join(f"{x:.2f}" for x in k["choice effect, rewarded"]))
    return lines + ["", f"Checks: {i8['checks']}.", "", "![I8](../fig_I8_v_tests.png)"]


def main() -> None:
    text = REPORT.read_text()
    pattern = re.compile(re.escape(BEGIN) + r".*?" + re.escape(END), re.S)
    if len(pattern.findall(text)) != 1:
        raise AssertionError(f"{REPORT.name} must contain exactly one {BEGIN} … {END} pair")
    REPORT.write_text(pattern.sub(lambda _: f"{BEGIN}\n{block()}\n{END}", text))
    print(f"Wrote {REPORT}")


if __name__ == "__main__":
    main()
