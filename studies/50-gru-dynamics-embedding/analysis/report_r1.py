"""r1: regenerate the numbers block of ``reports/r1-first-look.md`` from the committed B JSONs.

    python analysis/report_r1.py

Offline formatter: reads only committed JSON, rewrites what sits between the r1 markers,
leaves the prose outside them alone.
"""

from __future__ import annotations

import json
import re
from pathlib import Path

import numpy as np

ANALYSIS = Path(__file__).resolve().parent
REPORT = ANALYSIS / "reports" / "r1-first-look.md"
BEGIN, END = "<!-- BEGIN result-1 -->", "<!-- END result-1 -->"


def load(name: str) -> dict:
    return json.loads((ANALYSIS / name).read_text())


def block() -> str:
    a1, pca, b4, b5, b6, b7 = (load(n) for n in ("trial_states_C-s0.json", "b3_pca.json", "b4_update_maps.json",
                                                 "b5_outcome_triggered.json", "b6_tracking.json", "b7_decoders.json"))
    ex = a1["extraction"]
    lines = [
        "[regenerated by `analysis/report_r1.py` — do not edit by hand]",
        "",
        f"Model C seed 0, checkpoint step {ex['checkpoint_step']}: {ex['n_trials']:,} trials, "
        f"{ex['n_sessions']:,} eval sessions, {ex['n_subjects']} training mice. Recomputed likelihood "
        f"{a1['checks']['recomputed_eval_likelihood']:.7f} vs logged {a1['checks']['logged_eval_likelihood']:.7f}.",
        "",
        "| task (session table) | sessions |", "|---|---:|",
        *[f"| {k} | {v:,} |" for k, v in a1["sessions_by_task"].items()],
        "",
        "### B1–B2 Example sessions and units",
        "![B1](../fig_B1_example_sessions.png)",
        "![B2](../fig_B2_unit_heatmap.png)",
        "",
        "### B3 State space",
        f"PCA over all trials: PC1–6 explain "
        + ", ".join(f"{100 * v:.1f}%" for v in pca["variance_explained_ratio"][:6])
        + f"; participation ratio {pca['participation_ratio']:.2f}; PCs for 90/95/99% of variance: "
        + "/".join(str(v) for v in pca["n_pcs_for_variance"].values()) + ".",
        "",
        "![B3a](../fig_B3a_pca_variance.png)",
        "![B3b](../fig_B3b_state_space_p_right.png)",
        "![B3c](../fig_B3c_prev_outcome.png)",
        "![B3e](../fig_B3e_trajectories.png)",
        "![B3 PCs 5–6](../fig_B3_pc56_trial_position.png)",
        "![B3f](../fig_B3f_mice_over_embedding.png)",
        "",
        "### B4 Update maps",
        "Mean logit(right) on trial t+1 when logit(right) on trial t was −3 / 0 / +3:",
        "",
        "| trial t | −3 | 0 | +3 |", "|---|---:|---:|---:|",
    ]
    for label, panel in b4["panels"].items():
        c = np.asarray(panel["bin_centres"], dtype=float)
        m = np.asarray(panel["mean_next_logit"], dtype=float)
        ok = np.isfinite(m)
        lines.append(f"| {label} | " + " | ".join(f"{np.interp(v, c[ok], m[ok]):+.2f}" for v in (-3, 0, 3)) + " |")
    lines += ["", "![B4](../fig_B4_update_maps.png)", "", "### B5 Outcome-triggered",
              "Reward effect on logit(right) (rewarded − unrewarded, same choice, matched on logit(t)), k = 1 / 5 / 10:",
              "", "| | k=1 | k=5 | k=10 |", "|---|---:|---:|---:|"]
    effect = b5["reward_effect_matched"]
    for side in ("right", "left"):
        v = effect[side]["all"]
        lines.append(f"| chose {side}, all tasks | {v[0]:+.2f} | {v[4]:+.2f} | {v[9]:+.2f} |")
    for task, v in effect["right"]["by_task"].items():
        lines.append(f"| chose right, {task} | {v[0]:+.2f} | {v[4]:+.2f} | {v[9]:+.2f} |")
    raw = b5["conditions_raw"]
    gap = max(abs(a - b) for c in raw.values() for a, b in zip(c["p_model"], c["p_animal"]))
    lines += ["", f"Model vs animal P(right) on trials t+1…t+10, largest gap over the four conditions: {gap:.4f}.",
              "", "![B5](../fig_B5_outcome_triggered.png)", "", "### B6 Tracking",
              f"Steady state (≥{b6['steady_after_trials']} trials after a probability change), |model − animal| P(right) per bin:",
              "", "| task | mean | max |", "|---|---:|---:|"]
    for task, v in b6["tasks"].items():
        a = np.asarray(v["steady"]["animal"], dtype=float)
        m = np.asarray(v["steady"]["model"], dtype=float)
        ok = np.isfinite(a) & np.isfinite(m)
        lines.append(f"| {task} | {np.mean(np.abs(a[ok] - m[ok])):.4f} | {np.max(np.abs(a[ok] - m[ok])):.4f} |")
    lines += ["", "![B6](../fig_B6_tracking.png)", "", "### B7 Decoders",
              f"{b7['n_trials']:,} trials, {b7['cv']}; signal location from activation patterns.", "",
              "| variable | R² | unique R² | share on PC1 | PC2 | PC1–4 |", "|---|---:|---:|---:|---:|---:|"]
    for r in b7["decoders"]:
        unique = f"{r['unique_cv_r2']:.3f}" if r["unique_cv_r2"] is not None else "—"
        share = r["signal_share_by_pc"]
        lines.append(f"| {r['variable']} | {r['cv_r2']:.3f} | {unique} | {share[0]:.2f} | {share[1]:.2f} | "
                     f"{r['signal_share_top4_pcs']:.2f} |")
    lines += ["", "![B7](../fig_B7_decoders.png)"]
    return "\n".join(lines)


def main() -> None:
    text = REPORT.read_text()
    pattern = re.compile(re.escape(BEGIN) + r".*?" + re.escape(END), re.S)
    if len(pattern.findall(text)) != 1:
        raise AssertionError(f"{REPORT.name} must contain exactly one {BEGIN} … {END} pair")
    REPORT.write_text(pattern.sub(lambda _: f"{BEGIN}\n{block()}\n{END}", text))
    print(f"Wrote {REPORT}")


if __name__ == "__main__":
    main()
