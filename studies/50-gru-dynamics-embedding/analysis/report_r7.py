"""r7: regenerate the numbers block of ``reports/r7-robustness.md`` from G1 and G3.

    python analysis/report_r7.py
"""

from __future__ import annotations

import json
import re
from pathlib import Path

ANALYSIS = Path(__file__).resolve().parent
REPORT = ANALYSIS / "reports" / "r7-robustness.md"
BEGIN, END = "<!-- BEGIN result-7 -->", "<!-- END result-7 -->"


def mark(value) -> str:
    return "✓" if value is True else ("✗" if value is False else f"— ({value})")


def cell(text: str) -> str:
    return text.replace("|", "\\|")


def block() -> str:
    g1 = json.loads((ANALYSIS / "g1_seed_robustness.json").read_text())
    g3 = json.loads((ANALYSIS / "g3_cross_seed_alignment.json").read_text())
    keys = g1["seeds"]
    lines = ["[regenerated by `analysis/report_r7.py` — do not edit by hand]", "",
             "### G1 claims (criteria fixed from seed 0's numbers before seeds 1–2 were seen)", "",
             "| claim | " + " | ".join(keys) + " |", "|---|" + "---|" * len(keys)]
    lines += [f"| {cell(c['claim'])} | " + " | ".join(mark(c[k]) for k in keys) + " |" for c in g1["claims"]]
    lines += ["", "### G1 numbers", "", "| metric | " + " | ".join(keys) + " | range / mean |",
              "|---|" + "---:|" * (len(keys) + 1)]
    for name, rec in g1["spread"].items():
        lines.append(f"| {cell(name)} | " + " | ".join(f"{v:.4g}" for v in rec["values"]) + f" | {rec['rel_range']:.1%} |")
    lines += ["", "### G3 cross-seed alignment", "",
              "| pair | logit r | mean \\|ΔP(right)\\| | mean \\|Δ log-lik\\| (nats) | v r | state CCA 1–4 | state CCA 5–8 | "
              "PCs 1–4 R² from other state | embedding CCA | embedding distance ρ |",
              "|---|---:|---:|---:|---:|---|---|---|---|---:|"]
    for pair, r in g3["pairs"].items():
        cca = r["state_cca_top10"]
        lines.append(f"| {pair} | {r['logit_corr']:.4f} | {r['p_right_mean_abs_diff']:.4f} | {r['ll_mean_abs_diff_nats']:.4f} | "
                     f"{r['v_corr']:.3f} | {', '.join(f'{x:.3f}' for x in cca[:4])} | {', '.join(f'{x:.3f}' for x in cca[4:8])} | "
                     f"{', '.join(f'{x:.3f}' for x in r['pcs1_4_r2_from_other_state'])} | "
                     f"{', '.join(f'{x:.3f}' for x in r['embedding_cca'])} | {r['embedding_distance_spearman']:.3f} |")
    ref = g3["reference_seed0_vs_ctt"]
    lines.append(f"| C-s0 vs CTT (scale reference) | {g3['reference_gru_ctt_corr_logit']:.4f} | {ref['p_right_mean_abs_diff']:.4f} | "
                 f"{ref['ll_mean_abs_diff_nats']:.4f} | | | | | | |")
    lines += ["", "| seed | η² of PC1–4 by last input | η² of PC1–4 by last choice | η² of PC1 by last choice |",
              "|---|---:|---:|---:|"]
    for k, r in g3["per_seed"].items():
        lines.append(f"| {k} | {r['eta2_pc1_4_last_input']:.3f} | {r['eta2_pc1_4_last_choice']:.3f} | {r['eta2_pc1_last_choice']:.3f} |")
    lines += ["", "![G1](../fig_G1_seed_robustness.png)", "![G3a](../fig_G3a_state_space_by_seed.png)",
              "![G3b](../fig_G3b_cross_seed_alignment.png)"]
    return "\n".join(lines)


def main() -> None:
    text = REPORT.read_text()
    pattern = re.compile(re.escape(BEGIN) + r".*?" + re.escape(END), re.S)
    if len(pattern.findall(text)) != 1:
        raise AssertionError(f"{REPORT.name} must contain exactly one {BEGIN} … {END} pair")
    REPORT.write_text(pattern.sub(lambda _: f"{BEGIN}\n{block()}\n{END}", text))
    print(f"Wrote {REPORT}")


if __name__ == "__main__":
    main()
