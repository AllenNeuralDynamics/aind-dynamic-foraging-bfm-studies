"""r3: regenerate the numbers block of ``reports/r3-dynamics.md`` from ``d_dynamics.json``.

    python analysis/report_r3.py

Offline formatter: reads only committed JSON (this study's and Study 50's), rewrites what
sits between the r3 markers, leaves the prose outside them alone.
"""

from __future__ import annotations

import json
import re
from pathlib import Path

ANALYSIS = Path(__file__).resolve().parent
STUDY12 = ANALYSIS.parents[1] / "50-gru-dynamics-embedding" / "analysis"
REPORT = ANALYSIS / "reports" / "r3-dynamics.md"
BEGIN, END = "<!-- BEGIN result-1 -->", "<!-- END result-1 -->"
C_INPUT_NAMES = {"R+": "R rewarded", "R−": "R unrewarded", "L+": "L rewarded", "L−": "L unrewarded"}
K_SHOWN = (1, 2, 3, 5, 10, 20, 30)


def _taus(fp: dict, key: str) -> str:
    return ", ".join(f"{v:.1f}" for v in fp[key][:3] if v is not None) or "—"


def block() -> str:
    d = json.loads((ANALYSIS / "d_dynamics.json").read_text())
    c = json.loads((STUDY12 / "d_dynamics.json").read_text())["contexts"]["all sessions"]["inputs"]
    r = d["relaxation"]
    lines = [
        "[regenerated by `analysis/report_r3.py` — do not edit by hand]",
        "",
        "Step parity (median / max |Δ| vs A1, first {} sessions): ".format(d["parity_sessions"])
        + "; ".join(f"{n} {v['median_abs_err']:.1e} / {v['max_abs_err']:.1e}" for n, v in d["parity"].items()) + ".",
        "",
        "### D2 Fixed points of each constant input (mean context)",
        "",
        "| input | model | fixed point | side logit | P(ignore) | stable | three slowest τ (steps) | slowest mode overlap: side / engage |",
        "|---|---|---|---:|---:|---|---|---|",
    ]
    for uname, rec in d["fixed_points"].items():
        for i, fp in enumerate(rec["fixed_points"]):
            ov = fp["slow_mode_overlap"][0]
            lines.append(f"| {uname} | C3 | {i + 1} | {fp['side_logit']:+.2f} | {fp['p_ignore']:.3f} | "
                         f"{'yes' if fp['stable'] else 'no'} | {_taus(fp, 'tau_steps')} | {ov['side']:.2f} / {ov['engage']:.2f} |")
        if uname in C_INPUT_NAMES:
            for i, fp in enumerate(c[C_INPUT_NAMES[uname]]["fixed_points"]):
                lines.append(f"| {uname} | C | {i + 1} | {fp['logit_right']:+.2f} | — | {'yes' if fp['stable'] else 'no'} | "
                             f"{_taus(fp, 'tau_trials')} | — |")
    lines += [
        "",
        "Share of fixed-point candidates that converged: " + "; ".join(
            f"{u} {rec['frac_candidates_converged']:.0%}" for u, rec in d["fixed_points"].items()) + ".",
        "",
        "![D1](../fig_D1_flow_fields.png)",
        "![D2](../fig_D2_fixed_points.png)",
        "",
        f"### D3 Relaxation under repeated ignores ({r['n_states']:,} real engaged states, own contexts)",
        "",
        f"At the start: median |side logit| {r['start']['side_abs_median']:.2f}, mean P(ignore) {r['start']['p_ignore_mean']:.3f}. "
        f"Side preference halves after {r['k_to_half_side_preference']} ignores.",
        "",
        "| consecutive inputs | " + " | ".join(str(k) for k in K_SHOWN) + " |",
        "|---|" + "---:|" * len(K_SHOWN),
        "| ignores: \\|side\\| / start (median) | " + " | ".join(f"{r['side_abs_fraction_of_start_median'][k - 1]:.2f}" for k in K_SHOWN) + " |",
        "| ignores: mean P(ignore) | " + " | ".join(f"{r['p_ignore_mean'][k - 1]:.3f}" for k in K_SHOWN) + " |",
        "| then unrewarded choices: mean P(ignore) | " + " | ".join(f"{r['recovery_p_ignore_mean'][k - 1]:.3f}" for k in K_SHOWN) + " |",
        "| then unrewarded choices: side toward that side (median) | "
        + " | ".join(f"{r['recovery_side_toward_favoured_median'][k - 1]:+.2f}" for k in K_SHOWN) + " |",
        "",
        "![D3](../fig_D3_relaxation.png)",
    ]
    return "\n".join(lines)


def main() -> None:
    text = REPORT.read_text()
    pattern = re.compile(re.escape(BEGIN) + r".*?" + re.escape(END), re.S)
    if not pattern.search(text):
        raise AssertionError(f"{REPORT} lacks the {BEGIN} / {END} markers")
    REPORT.write_text(pattern.sub(lambda _: f"{BEGIN}\n{block()}\n{END}", text))


if __name__ == "__main__":
    main()
