"""r7: regenerate the numbers block of ``reports/r7-robustness.md`` from G1's JSONs.

    python analysis/report_r7.py

Offline formatter: reads only committed JSON, rewrites what sits between the r7 markers.
"""

from __future__ import annotations

import json
import re
from pathlib import Path

ANALYSIS = Path(__file__).resolve().parent
REPORT = ANALYSIS / "reports" / "r7-robustness.md"
BEGIN, END = "<!-- BEGIN result-1 -->", "<!-- END result-1 -->"


def block() -> str:
    g = json.loads((ANALYSIS / "g_seeds.json").read_text())["metrics"]
    dyn = json.loads((ANALYSIS / "g_dynamics.json").read_text())["seeds"]
    seeds = list(g)
    gaps = list(next(iter(g.values()))["by_gap"])
    head = "| metric | " + " | ".join(seeds) + " |"
    sep = "|---|" + "---:|" * len(seeds)

    def row(label, fn, fmt="{:.4f}"):
        return f"| {label} | " + " | ".join(fmt.format(fn(k)) for k in seeds) + " |"

    lines = ["[regenerated by `analysis/report_r7.py` — do not edit by hand]", "",
             "### Side prediction vs C (seed 0), shared engaged trials", "", head, sep,
             row("L/R likelihood, C3", lambda k: g[k]["lr_likelihood"]["C3"]),
             row("L/R likelihood, C", lambda k: g[k]["lr_likelihood"]["C"]),
             *[row(f"C3 − C per trial, gap {gp}", lambda k, gp=gp: g[k]["by_gap"][gp]["C3_minus_C_per_trial"], "{:+.4f}") for gp in gaps],
             "", "### Behaviour, kernels, engagement", "", head, sep,
             row("max \\|C3 − animal\\| P(stay) over gaps", lambda k: g[k]["stay_max_abs_gap_C3_vs_animal"]),
             *[row(f"lag-1 rewarded-choice weight after gap {gp} (× no gap)",
                   lambda k, gp=gp: g[k]["kernel_lag1_ratio_to_gap0"][gp]["RewC"], "{:.2f}") for gp in gaps[1:]],
             row("ignore rule λ (v ← λ v + c)", lambda k: g[k]["ignore_rule_lambda"], "{:.3f}"),
             row("calibration, max \\|obs − pred\\| over bins", lambda k: g[k]["calibration_max_abs_gap"]),
             row("P(ignore \\| previous ignored), model (obs {:.3f})".format(next(iter(g.values()))["p_ignore_after_ignore"]["observed"]),
                 lambda k: g[k]["p_ignore_after_ignore"]["model"], "{:.3f}"),
             row("ignore rate from the embedding, CV R² (C: 0.011)", lambda k: g[k]["embedding_decodes_ignore_rate_cv_r2"], "{:.3f}"),
             "", f"### Dynamics (mean context; relaxation from 5,000 engaged states, own contexts)", "",
             "| metric | " + " | ".join(dyn) + " |", "|---|" + "---:|" * len(dyn),
             *[f"| {name} attractor: side logit / P(ignore) | " + " | ".join(
                 f"{dyn[k]['attractors_mean_context'][name]['side_logit']:+.2f} / {dyn[k]['attractors_mean_context'][name]['p_ignore']:.3f}"
                 for k in dyn) + " |" for name in next(iter(dyn.values()))["attractors_mean_context"]],
             *[f"| \\|side\\| after {kk} ignores (× start) | " + " | ".join(
                 f"{dyn[k]['relaxation_side_fraction_median'][kk]:.2f}" for k in dyn) + " |"
               for kk in next(iter(dyn.values()))["relaxation_side_fraction_median"]],
             *[f"| P(ignore) after {kk} ignores | " + " | ".join(
                 f"{dyn[k]['relaxation_p_ignore_mean'][kk]:.3f}" for k in dyn) + " |"
               for kk in next(iter(dyn.values()))["relaxation_p_ignore_mean"]],
             "", "![G1](../fig_G1_seeds.png)"]
    return "\n".join(lines)


def main() -> None:
    text = REPORT.read_text()
    pattern = re.compile(re.escape(BEGIN) + r".*?" + re.escape(END), re.S)
    if not pattern.search(text):
        raise AssertionError(f"{REPORT} lacks the {BEGIN} / {END} markers")
    REPORT.write_text(pattern.sub(lambda _: f"{BEGIN}\n{block()}\n{END}", text))


if __name__ == "__main__":
    main()
