"""r5: regenerate the numbers block of ``reports/r5-embedding.md`` from ``f_engagement_embedding.json``.

    python analysis/report_r5.py

Offline formatter: reads only committed JSON, rewrites what sits between the r5 markers.
"""

from __future__ import annotations

import json
import re
from pathlib import Path

ANALYSIS = Path(__file__).resolve().parent
REPORT = ANALYSIS / "reports" / "r5-embedding.md"
BEGIN, END = "<!-- BEGIN result-1 -->", "<!-- END result-1 -->"


def block() -> str:
    f = json.loads((ANALYSIS / "f_engagement_embedding.json").read_text())
    feats = list(f["decode_cv_r2"])
    lines = ["[regenerated by `analysis/report_r5.py` — do not edit by hand]", "",
             f"{f['n_mice']} mice with ≥ {f['min_ignored_steps_per_mouse']} ignored eval steps.", "",
             "| per-mouse feature | median | range | CV R² from C3's embedding | from C's embedding |",
             "|---|---:|---|---:|---:|"]
    for name in feats:
        s = f["feature_summary"][name]
        lines.append(f"| {name} | {s['50%']:.3f} | {s['min']:.3f} – {s['max']:.3f} | "
                     f"{f['decode_cv_r2'][name]['C3']:.3f} | {f['decode_cv_r2'][name]['C']:.3f} |")
    lines += ["", "C3's ignore dynamics at each mouse's own context (across mice):", "",
              "| quantity | mean | range | " + " | ".join(f"r with {n}" for n in feats) + " |",
              "|---|---:|---|" + "---:|" * len(feats)]
    for name, s in f["mouse_dynamics_summary"].items():
        r = f["corr_mouse_dynamics_vs_observed"][name]
        lines.append(f"| {name} | {s['mean']:.3f} | {s['min']:.3f} – {s['max']:.3f} | "
                     + " | ".join(f"{r[n]:+.2f}" for n in feats) + " |")
    lines += ["", f"Largest per-step change after {f['n_iter_attractor']} ignore iterations: "
              f"{f['attractor_max_residual']:.1e} (slowest modes τ ≈ 500 steps; r3).", "",
              "![F](../fig_F_engagement_embedding.png)"]
    return "\n".join(lines)


def main() -> None:
    text = REPORT.read_text()
    pattern = re.compile(re.escape(BEGIN) + r".*?" + re.escape(END), re.S)
    if not pattern.search(text):
        raise AssertionError(f"{REPORT} lacks the {BEGIN} / {END} markers")
    REPORT.write_text(pattern.sub(lambda _: f"{BEGIN}\n{block()}\n{END}", text))


if __name__ == "__main__":
    main()
