"""r4: regenerate the numbers block of ``reports/r4-subspaces.md`` from ``e2_ablations.json``.

    python analysis/report_r4.py

Offline formatter: reads only committed JSON, rewrites what sits between the r4 markers.
"""

from __future__ import annotations

import json
import re
from pathlib import Path

ANALYSIS = Path(__file__).resolve().parent
REPORT = ANALYSIS / "reports" / "r4-subspaces.md"
BEGIN, END = "<!-- BEGIN result-1 -->", "<!-- END result-1 -->"


def block() -> str:
    e = json.loads((ANALYSIS / "e2_ablations.json").read_text())
    intact = e["results"]["intact"]
    lines = ["[regenerated by `analysis/report_r4.py` — do not edit by hand]", "",
             f"{e['n_sessions']:,} random eval sessions ({intact['n_engaged']:,} engaged trials, {intact['n_steps']:,} steps); "
             f"intact replay matches A1 to {e['parity_median_abs_err']:.1e} (median). Intact: L/R {intact['LR_engaged']:.4f}, "
             f"engage {intact['engage']:.4f}, 3-way {intact['three_way']:.4f}. Cosine between the side and engage "
             f"directions: {e['cosine_side_engage']:.2f}.", "",
             "| ablated subspace | mode | L/R likelihood | engage likelihood | 3-way | L/R lost | engage lost |",
             "|---|---|---:|---:|---:|---:|---:|"]
    for key, r in e["results"].items():
        if key == "intact":
            continue
        name, mode = key.split(" | ")
        c = e["cost_vs_intact"][key]
        lines.append(f"| {name} | {mode} | {r['LR_engaged']:.4f} | {r['engage']:.4f} | {r['three_way']:.4f} | "
                     f"{c['LR_engaged']:+.4f} | {c['engage']:+.4f} |")
    lines += ["", "![E2](../fig_E2_ablations.png)"]
    return "\n".join(lines)


def main() -> None:
    text = REPORT.read_text()
    pattern = re.compile(re.escape(BEGIN) + r".*?" + re.escape(END), re.S)
    if not pattern.search(text):
        raise AssertionError(f"{REPORT} lacks the {BEGIN} / {END} markers")
    REPORT.write_text(pattern.sub(lambda _: f"{BEGIN}\n{block()}\n{END}", text))


if __name__ == "__main__":
    main()
