from pathlib import Path

ANALYSIS = Path(__file__).resolve().parent
STUDY12 = ANALYSIS.parents[1] / "50-gru-dynamics-embedding" / "analysis"
REPORT = ANALYSIS / "reports" / "r1-first-look.md"
BEGIN, END = "<!-- BEGIN result-1 -->", "<!-- END result-1 -->"


def load(name: str, folder: Path = ANALYSIS) -> dict:
    return json.loads((folder / name).read_text())


def _at(entry: dict, x: float) -> float:
    centres = entry["bin_centres"]
    return entry["mean_next"][min(range(len(centres)), key=lambda i: abs(centres[i] - x))]


def _max_gap(rows: dict) -> float:
    gaps = [abs(m - a) for m, a in zip(rows["model"], rows["animal"]) if m is not None and a is not None
            and m == m and a == a]
    return max(gaps)


