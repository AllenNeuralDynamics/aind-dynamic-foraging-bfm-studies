"""r2: regenerate the numbers block of ``reports/r2-vs-animals-and-2way.md`` from the committed C JSONs.

    python analysis/report_r2.py

Offline formatter: reads only committed JSON, rewrites what sits between the r2 markers,
leaves the prose outside them alone.
"""

from __future__ import annotations

import json
import re
from pathlib import Path

ANALYSIS = Path(__file__).resolve().parent
STUDY12 = ANALYSIS.parents[1] / "50-gru-dynamics-embedding" / "analysis"
REPORT = ANALYSIS / "reports" / "r2-vs-animals-and-2way.md"
BEGIN, END = "<!-- BEGIN result-1 -->", "<!-- END result-1 -->"
K_SHOWN = (1, 2, 3, 5, 10)


def load(name: str, folder: Path = ANALYSIS) -> dict:
    return json.loads((folder / name).read_text())


def row(label: str, values, fmt: str = "{:+.3f}") -> str:
    return f"| {label} | " + " | ".join(fmt.format(values[k - 1]) for k in K_SHOWN) + " |"


def block() -> str:
    c2, c4, c1k, c1 = (load(n) for n in ("c2_compare.json", "c4_after_ignore.json", "c1_kernels.json", "c1_impulse.json"))
    c1_c = load("c1_impulse.json", STUDY12)
    models = ["C3", "C", "ctt", "bari", "hattori"]
    pm = c2["per_mouse"]
    lines = [
        "[regenerated by `analysis/report_r2.py` — do not edit by hand]",
        "",
        "### C2 Side-choice likelihood on the shared engaged trials",
        "",
        "| trials | n | " + " | ".join(models) + " |", "|---|---:|" + "---:|" * len(models),
        *[f"| {g} | {v['n']:,} | " + " | ".join(f"{v[m]:.4f}" for m in models) + " |"
          for g, v in c2["pooled_likelihood"].items()],
        "",
        f"Per mouse ({pm['n_mice']}): C3 > C in {pm['C3_minus_C_share_positive']:.0%} (median Δ {pm['C3_minus_C_median']:+.4f}); "
        f"C3 > every RL model in {pm['C3_minus_best_rl_share_positive']:.0%}.",
        "",
        "| ignored just before (gap) | trials | mice | C3 | C | CTT | C3 − C per trial (nats, mean over mice ± 1.96 SEM) | mice with C3 > C |",
        "|---|---:|---:|---:|---:|---:|---:|---:|",
        *[f"| {g} | {v['n_trials']:,} | {v['n_mice']} | {v['C3']:.3f} | {v['C']:.3f} | {v['ctt']:.3f} | "
          f"{v['C3_minus_C_per_trial_mean_over_mice']:+.4f} ± {1.96 * v['C3_minus_C_sem']:.4f} | "
          f"{v['C3_minus_C_share_mice_positive']:.0%} |" for g, v in c2["by_gap"].items()],
        "",
        "![C2](../fig_C2_likelihood.png)",
        "",
        "### C4 Repeating the previous engaged choice after a gap",
        "",
        "| previous outcome | gap | n | animal | C3 | C | CTT | confidence C3 | confidence C |",
        "|---|---|---:|---:|---:|---:|---:|---:|---:|",
        *[f"| {o} | {g} | {v['n']:,} | {v['animal']:.3f} | {v['C3']:.3f} | {v['C']:.3f} | {v['ctt']:.3f} | "
          f"{v['confidence_C3']:.3f} | {v['confidence_C']:.3f} |"
          for o in ("rewarded", "unrewarded") for g, v in c4["by_previous_outcome_and_gap"][o].items()],
        "",
        "![C4](../fig_C4_after_ignore.png)",
        "",
        "### C1b History kernels by gap (Su2022, 10 engaged trials back)",
        "",
        "Lag-1 weight as a fraction of its value at gap 0 (rewarded / unrewarded choice):",
        "",
        "| source | " + " | ".join(c1k["lag1_ratio_to_gap0"]["animal"]) + " |",
        "|---|" + "---:|" * len(c1k["lag1_ratio_to_gap0"]["animal"]),
        *[f"| {s} | " + " | ".join(f"{v['RewC']:.2f} / {v['UnrC']:.2f}" for v in r.values()) + " |"
          for s, r in c1k["lag1_ratio_to_gap0"].items()],
        "",
        "Lag-1 weights at gap 0: " + "; ".join(
            f"{s} {k['RewC'][0]:.2f} / {k['UnrC'][0]:.2f}" for s, k in c1k["kernels"]["0"].items()) + ".",
        "",
        "![C1 kernels](../fig_C1_kernels.png)",
        "",
        "### C1a Counterfactual edits (one trial's input; later inputs as observed)",
        "",
        f"Replay check: side median |err| {c1['replay_check']['side']['median_abs_err']:.1e}, engage "
        f"{c1['replay_check']['engage']['median_abs_err']:.1e}. Ignored trials enter as (choice 2, reward 0): "
        f"checked on {c1['ignore_encoding_check']['n_ignored_with_next_row']:,} rows.",
        "",
        "| effect (mean over 20,000 edits) | k = 1 | 2 | 3 | 5 | 10 |", "|---|---:|---:|---:|---:|---:|",
        row("reward flip → side, C3", c1["reward_flip"]["side"]["mean"]),
        row("reward flip → side, C (Study 50)", c1_c["all"]["mean"]),
        row("reward flip → engage, C3", c1["reward_flip"]["engage"]["mean"]),
        row("engaged → ignore → side (was rewarded)", c1["to_ignore_by_original_reward"]["was_rewarded"]["side"]["mean"]),
        row("engaged → ignore → side (was unrewarded)", c1["to_ignore_by_original_reward"]["was_unrewarded"]["side"]["mean"]),
        row("engaged → ignore → engage (was rewarded)", c1["to_ignore_by_original_reward"]["was_rewarded"]["engage"]["mean"]),
        row("engaged → ignore → engage (was unrewarded)", c1["to_ignore_by_original_reward"]["was_unrewarded"]["engage"]["mean"]),
        row("ignore → unrewarded choice → side", c1["to_engaged"]["side"]["mean"]),
        row("ignore → unrewarded choice → engage", c1["to_engaged"]["engage"]["mean"]),
        "",
        "![C1 impulse](../fig_C1_impulse.png)",
    ]
    return "\n".join(lines)


def main() -> None:
    text = REPORT.read_text()
    pattern = re.compile(re.escape(BEGIN) + r".*?" + re.escape(END), re.S)
    if not pattern.search(text):
        raise AssertionError(f"{REPORT} lacks the {BEGIN} / {END} markers")
    REPORT.write_text(pattern.sub(lambda _: f"{BEGIN}\n{block()}\n{END}", text))


if __name__ == "__main__":
    main()
