#!/usr/bin/env python
"""Write the refit and rescore manifests (and the rescore's draws index) from the frozen run table.

PLAN.md allows one refit, with longer chains and the centred session level, for every subject that
fails the gates: R-hat >= 1.01, bulk ESS < 400, or any divergence. Every other subject keeps its fit
and is rescored from its saved draws, so the sessions failing Pareto k-hat get the importance-sampled
session-marginal (ADR 0004). Subjects come from ``analysis/hattori_runs.json`` (finished runs of
``hattori@20261026-002131``), never retyped; rerunning this regenerates identical files.

    python variants/hattori/make_refit_rescore.py
"""
from __future__ import annotations

import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
RUNS = HERE.parents[1] / "analysis" / "hattori_runs.json"
ARTIFACT_ROOT = "/home/han.hou/outputs/disrnn/hb_artifacts"
# The pinned, clean studies checkout the rescore launches from; the wrapper reads the index there.
LAUNCH_CHECKOUT = "/home/han.hou/code/wt/hpc13c/aind-dynamic-foraging-bfm-studies"
GATE_MAX_R_HAT, GATE_MIN_ESS_BULK = 1.01, 400.0

SHARED = """entity: AIND-disRNN
project: mice_data_scaling
name: {name}

method: grid
metric:
  name: heldout/eval_likelihood
  goal: maximize

command:
  - python
  - -m
  - run_hpc
  - data=mice_snapshot_scaling
  - model=hb_hattori
  - model.estimator=heldout_two_level
{extra}  - +model.importance_rescore=true
  - +model.importance_draws=24000
  - data.subject_ratio=0.016
  - seed=0
  - wandb.entity=AIND-disRNN
  - wandb.project=mice_data_scaling
  - ${{args_no_hyphens}}

parameters:
  data.test_subject_ids:
    values:
{values}"""

REFIT = """  - model.num_warmup=3000
  - model.num_samples=3000
  - model.num_chains=4
  - model.target_accept_prob=0.95
  - +model.centered=true
  - +model.session_draws_per_posterior_draw=12
"""
RESCORE = """  - model.num_warmup=2000
  - model.num_samples=1500
  - model.num_chains=4
  - +model.session_draws_per_posterior_draw=24
  - +model.draws_path={index}
"""

HEADER_REFIT = """# Refit: one per subject that failed the gates in hattori@20261026-002131 (R-hat >= 1.01, bulk ESS
# < 400, or any divergence), as PLAN.md allows. Centred session level, target acceptance 0.95,
# 3000 warmup + 4 x 3000 draws (12,000 posterior draws), 12 session draws per posterior draw so each
# session-marginal still rests on 144,000 draws, as in production, at production's scoring memory.
# Sessions failing Pareto k-hat are rescored by importance sampling (ADR 0004).
# Generated by make_refit_rescore.py from analysis/hattori_runs.json; do not edit by hand.
"""
HEADER_RESCORE = """# Rescore: every subject that passed the gates keeps its production fit. Its saved draws
# (draws_index.json -> hb_artifacts/<run id>) are scored again with production's seed and settings,
# which reproduces the plain scores exactly; sessions failing Pareto k-hat are then rescored by
# importance sampling (ADR 0004). Nothing is refitted.
# Generated by make_refit_rescore.py from analysis/hattori_runs.json; do not edit by hand.
"""


def _passes(row: dict) -> bool:
    return (row["hb/max_r_hat"] < GATE_MAX_R_HAT and row["hb/min_ess_bulk"] >= GATE_MIN_ESS_BULK
            and row["hb/divergences"] == 0)


def main() -> None:
    rows = [r for r in json.loads(RUNS.read_text())["rows"] if r["state"] == "finished"]
    subjects = [r["subject_id"] for r in rows]
    assert len(subjects) == len(set(subjects)) == 149, "expected one finished run per subject"
    refit = sorted(r["subject_id"] for r in rows if not _passes(r))
    keep = sorted((r["subject_id"], r["wandb_run_id"]) for r in rows if _passes(r))

    index = HERE / "draws_index.json"
    index.write_text(json.dumps({s: f"{ARTIFACT_ROOT}/{run}" for s, run in keep}, indent=1) + "\n")

    def values(ids):
        return "".join(f'      - "[{s}]"\n' for s in ids)

    (HERE / "sweep_hpc_refit.yaml").write_text(HEADER_REFIT + SHARED.format(
        name="hb-heldout-two-level-refit", extra=REFIT, values=values(refit)))
    (HERE / "sweep_hpc_rescore.yaml").write_text(HEADER_RESCORE + SHARED.format(
        name="hb-heldout-two-level-rescore",
        extra=RESCORE.format(index=f"{LAUNCH_CHECKOUT}/{index.relative_to(HERE.parents[3])}"),
        values=values([s for s, _ in keep])))
    print(f"refit {len(refit)} subjects, rescore {len(keep)}")


if __name__ == "__main__":
    main()
