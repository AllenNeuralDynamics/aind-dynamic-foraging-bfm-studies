#!/usr/bin/env python
"""Write the ctt refit manifest from the frozen run table (``analysis/ctt_runs.json``).

Applies the hattori variant's refit (ADR 0004, approved by Han): every subject failing a gate
(R-hat >= 1.01, bulk ESS < 400, or any divergence) is refit once, non-centred, at target acceptance
0.95 with 3000 warmup + 4 x 3000 draws and 12 session draws per posterior draw. Subjects come from
the freeze, never retyped; rerunning this regenerates the same file.

    python variants/ctt/make_refit.py
"""
from __future__ import annotations

import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
RUNS = HERE.parents[1] / "analysis" / "ctt_runs.json"
TEMPLATE = HERE / "sweep_hpc_per_subject.yaml"


def main() -> None:
    rows = [r for r in json.loads(RUNS.read_text())["rows"] if r["state"] == "finished"]
    failing = sorted(r["subject_id"] for r in rows
                     if not (r["hb/max_r_hat"] < 1.01 and r["hb/min_ess_bulk"] >= 400
                             and r["hb/divergences"] == 0))
    body = TEMPLATE.read_text().split("entity:", 1)[1].split("    values:\n", 1)[0]
    for old, new in [("model.num_warmup=2000", "model.num_warmup=3000"),
                     ("model.num_samples=1500", "model.num_samples=3000\n  - model.target_accept_prob=0.95"),
                     ("+model.session_draws_per_posterior_draw=24",
                      "+model.session_draws_per_posterior_draw=12"),
                     ("name: hb-ctt-heldout-two-level-per-subject", "name: hb-ctt-heldout-two-level-refit")]:
        assert old in body, old
        body = body.replace(old, new)
    header = ("# ctt refit: the subjects failing a gate in ctt@20261028-003745, refit as the hattori\n"
              "# variant's (ADR 0004): non-centred, target acceptance 0.95, 3000 warmup + 4 x 3000 draws,\n"
              "# 12 session draws per posterior draw; k-hat rescue on.\n"
              "# Generated by make_refit.py from analysis/ctt_runs.json; do not edit by hand.\n")
    values = "".join(f'      - "[{s}]"\n' for s in failing)
    (HERE / "sweep_hpc_refit.yaml").write_text(header + "entity:" + body + "    values:\n" + values)
    print(f"refit {len(failing)} subjects")


if __name__ == "__main__":
    main()
